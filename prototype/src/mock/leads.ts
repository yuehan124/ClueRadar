import type { Identity, Lead, LeadActivity, LeadStatus, Platform, SignalKind, Stage } from '@/types'

const NOW = new Date('2026-10-19T09:30:00').getTime()

/**
 * 相对 NOW 的小时数 → 本地时间串（不含时区标记）。
 * 注意：不能用 toISOString()，那会写 UTC 时刻，而读取端 new Date() 按本地时区解析，
 * 会产生时区偏移（东八区会整体差 8 小时）。
 */
function ago(hours: number): string {
  const d = new Date(NOW - hours * 3600 * 1000)
  const p = (n: number) => String(n).padStart(2, '0')
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}T${p(d.getHours())}:${p(d.getMinutes())}:${p(d.getSeconds())}`
}

/** 时效性：越新越高，48 小时后基本衰减到最低 */
function freshnessOf(commentTime: string): number {
  const hours = (NOW - new Date(commentTime).getTime()) / 3600000
  return Math.max(10, Math.min(100, Math.round(100 - hours * 2)))
}

/** 互动热度：点赞 + 子评论 */
function engagementOf(likeCount: number, subComments = 0): number {
  return Math.max(10, Math.min(100, Math.round(30 + likeCount * 1.2 + subComments * 6)))
}

type RawSignal = [word: string, kind: SignalKind, weight: number, snippet: string]

interface LeadSeed {
  id: string
  platform: Platform
  creatorHash: string
  nickname: string
  commentId: string
  contentTitle: string
  contentUrl: string
  sourceKeyword: string
  commentText: string
  hoursAgo: number
  likeCount: number
  subComments?: number
  valid: boolean
  invalidReason?: string
  stage: Stage
  identity: Identity
  identityNote?: string
  needSummary: string
  competitors?: string[]
  signals: RawSignal[]
  intentStrength: number
  specificity: number
  status?: LeadStatus
  owner?: string
  activities?: LeadActivity[]
}

function make(seed: LeadSeed): Lead {
  const commentTime = ago(seed.hoursAgo)
  return {
    id: seed.id,
    platform: seed.platform,
    creatorHash: seed.creatorHash,
    nickname: seed.nickname,
    commentId: seed.commentId,
    contentId: `c_${seed.id.slice(2)}`,
    contentTitle: seed.contentTitle,
    contentUrl: seed.contentUrl,
    sourceKeyword: seed.sourceKeyword,
    commentText: seed.commentText,
    commentTime,
    likeCount: seed.likeCount,
    valid: seed.valid,
    invalidReason: seed.invalidReason,
    stage: seed.stage,
    identity: seed.identity,
    identityNote: seed.identityNote,
    needSummary: seed.needSummary,
    competitors: seed.competitors ?? [],
    signals: seed.signals.map(([word, kind, weight, snippet]) => ({ word, kind, weight, snippet })),
    intentStrength: seed.intentStrength,
    specificity: seed.specificity,
    freshness: freshnessOf(commentTime),
    engagement: engagementOf(seed.likeCount, seed.subComments ?? 0),
    status: seed.status ?? 'new',
    owner: seed.owner,
    activities: seed.activities ?? [],
  }
}

function act(hoursAgo: number, action: string, operator: string, note?: string): LeadActivity {
  return {
    id: `a_${hoursAgo}_${Math.random().toString(36).slice(2, 7)}`,
    time: ago(hoursAgo),
    action,
    operator,
    note,
  }
}

